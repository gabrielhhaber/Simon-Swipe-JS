/*
 * Generates js/sound-data.js: every sound in sounds/ embedded as a base64
 * data URI. It is only loaded when the game is opened straight from disk
 * (file://), where browsers block loading the .ogg files for Web Audio.
 * With the embedded data the game keeps Web Audio there too, so stereo
 * panning and smooth pitch changes work.
 *
 * Run after adding or changing any sound:
 *   node tools/build-sound-data.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const soundsDir = path.join(root, 'sounds');
const output = path.join(root, 'js', 'sound-data.js');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(soundsDir)
  .filter((file) => file.endsWith('.ogg'))
  .sort();

const lines = files.map((file) => {
  const key = path.relative(soundsDir, file).split(path.sep).join('/').replace(/\.ogg$/, '');
  const data = fs.readFileSync(file).toString('base64');
  return '  ' + JSON.stringify(key) + ': "data:audio/ogg;base64,' + data + '",';
});

const source = [
  '/* Generated by tools/build-sound-data.js - do not edit by hand. */',
  '(window.SimonSwipe = window.SimonSwipe || {}).SOUND_DATA = {',
  ...lines,
  '};',
  '',
].join('\n');

fs.writeFileSync(output, source);
console.log('Wrote ' + path.relative(root, output) + ' (' + files.length + ' sounds, ' +
  Math.round(source.length / 1024) + ' KB)');
